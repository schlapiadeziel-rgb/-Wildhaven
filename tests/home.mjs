import assert from 'node:assert/strict';
import {Game,BUILDS} from '../game/world.js';
const g=new Game();g.world.nodes=[];g.buildings=[];g.player.x=30;g.player.z=30;g.inventory={wood:999,stone:999,crystal:999,berry:999};
assert.equal(g.build('wall',30,31.5),false,'walls require a floor');
assert.equal(g.build('floor',30,30),true);
assert.equal(g.build('floor',30,30),false,'no duplicate floors');
const horizontal=g.snapBuild('wall',30.2,31.3,0),vertical=g.snapBuild('wall',31.3,30.2,Math.PI/2);
assert.deepEqual(horizontal,{x:30,z:31.5,angle:0},'horizontal wall snaps to a north/south floor edge');
assert.deepEqual(vertical,{x:31.5,z:30,angle:Math.PI/2},'vertical wall snaps to an east/west floor edge');
assert.equal(g.buildReason('wall',horizontal.x,horizontal.z,horizontal.angle),'','horizontal wall reports no placement problem');
assert.equal(g.buildReason('wall',vertical.x,vertical.z,vertical.angle),'','vertical wall reports no placement problem');
for(const [type,x,z,a] of [['door',30,31.5,0],['wall',30,28.5,0],['wall',31.5,30,Math.PI/2],['wall',28.5,30,Math.PI/2],['roof',30,30,0]])assert.equal(g.build(type,x,z,a),true,`${type} can attach`);
assert.equal(g.homeScore().rooms,1);
const floor=g.buildings.find(b=>b.type==='floor'),door=g.buildings.find(b=>b.type==='door');
assert.equal(g.buildingAction(floor.id,'recycle'),false,'cannot remove support');
assert.equal(g.buildingAction(floor.id,'upgrade'),true);assert.equal(floor.level,2);
const restored=new Game('adventure',JSON.parse(JSON.stringify(g.snapshot())));
assert.equal(restored.buildings.find(b=>b.id===floor.id).maxDurability,BUILDS.floor.maxDurability*2);
g.player.x=30;g.player.z=32.1;g.moveEntity(g.player,0,-.2);assert.equal(g.player.z,32.1,'closed door blocks');
assert.equal(g.buildingAction(door.id,'door'),true);g.moveEntity(g.player,0,-.2);assert(g.player.z<32.1,'open door allows passage');
assert.equal(g.buildingAction(door.id,'door'),false,'do not close on players');
g.player.x=30;g.player.z=30;
assert.equal(g.build('chest',30,30),true);
const chest=g.buildings.find(b=>b.type==='chest'),total=g.inventory.wood;
assert.equal(g.buildingAction(chest.id,'store','wood',10),true);
assert.equal(g.inventory.wood+chest.storage.wood,total);
assert.equal(g.buildingAction(chest.id,'recycle'),false,'nonempty chest protected');
assert.equal(g.buildingAction(chest.id,'store','wood',200),false,'capacity enforced');
assert.equal(g.buildingAction(chest.id,'take','wood',-2),false,'reject negative transfer');
g.player.id='visitor';assert.equal(g.buildingAction(chest.id,'take','wood',1),false,'owner permission enforced');
g.player.id=null;assert.equal(g.buildingAction(chest.id,'take','wood',10),true);assert.equal(g.inventory.wood,total);
assert.equal(g.buildingAction(chest.id,'recycle'),true);
for(const b of [...g.buildings].filter(b=>b.type!=='floor'))assert.equal(g.buildingAction(b.id,'recycle'),true);
assert.equal(g.buildingAction(floor.id,'recycle'),true);assert.equal(g.buildings.length,0);

const w=new Game();w.world.nodes=[];w.buildings=[];w.player.x=30;w.player.z=30;w.inventory={wood:999,stone:999,crystal:999,berry:999};
assert.equal(w.build('floor',30,30),true);
const south=w.snapBuild('wall',30,31.4,0);
assert.deepEqual(south,{x:30,z:31.5,angle:0});
assert.equal(w.build('wall',south.x,south.z,south.angle),true);
const other=w.snapBuild('wall',30.1,31.35,0);
assert.deepEqual(other,{x:30,z:28.5,angle:0},'occupied near edge yields the free horizontal edge');
assert.equal(w.buildReason('wall',other.x,other.z,other.angle),'');
assert.equal(w.build('wall',other.x,other.z,other.angle),true);
const stayed=w.snapBuild('wall',31.45,30.05,0);
assert.equal(stayed.angle,0,'horizontal request never becomes a vertical wall');
const sideWall=w.snapBuild('wall',31.4,30.1,Math.PI/2);
assert.equal(sideWall.angle,Math.PI/2);
assert.equal(w.build('wall',sideWall.x,sideWall.z,sideWall.angle),true);
w.player.x=32.2;w.player.z=30;
w.moveEntity(w.player,-.5,0);
assert.equal(w.player.x,32.2,'vertical wall blocks east-west movement');
const joined=w.snapBuild('fence',32.7,31.55,0);
assert.equal(joined.angle,0);
assert.ok(Math.abs(joined.x-32.8)<.05 && Math.abs(joined.z-31.5)<.05,`fence should meet the wall end, got ${JSON.stringify(joined)}`);
assert.equal(w.canBuild('fence',joined.x,joined.z,joined.angle),true,'fence can attach to a wall end');
assert.equal(w.build('fence',joined.x,joined.z,joined.angle),true);
const saved=new Game('adventure',JSON.parse(JSON.stringify(w.snapshot())));
assert.equal(saved.buildings.find(b=>b.x===31.5&&b.type==='wall').angle,Math.PI/2);
const legacy=JSON.parse(JSON.stringify(saved.snapshot()));
legacy.buildings.push({id:'legacy-wall',type:'wall',x:24,z:30,angle:0,durability:220,maxDurability:220});
const migrated=new Game('adventure',legacy);
assert.equal(migrated.buildings.find(b=>b.id==='legacy-wall').angle,0);
w.player.x=31.5;w.player.z=30;
assert.equal(w.buildingAction(w.buildings.find(b=>b.angle===Math.PI/2).id,'recycle'),true);
console.log('Home placement, enclosure, collision, upgrade/save, permissions, storage and recycling passed');
